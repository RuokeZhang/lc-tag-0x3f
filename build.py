def build_id_to_categories():
    """Returns {problem_id: [(main_category, sub_category), ...]}

    Applies MERGE_MAP so merged categories fold into their parents; the merged
    category's original name is prefixed onto each of its subcategories to avoid
    collisions and preserve context (e.g. "网格图·DFS").
    """
    result = defaultdict(list)
    for main_cat, subs in CATEGORIES.items():
        target_main = MERGE_MAP.get(main_cat, main_cat)
        prefix = f"{main_cat}·" if main_cat in MERGE_MAP else ""
        for sub_cat, ids in subs.items():
            display_sub = f"{prefix}{sub_cat}"
            for pid in ids:
                pair = (target_main, display_sub)
                if pair not in result[pid]:
                    result[pid].append(pair)
    return result


def get_main_categories():
    """Ordered list of main categories after merging."""
    seen = []
    for c in CATEGORIES.keys():
        target = MERGE_MAP.get(c, c)
        if target not in seen:
            seen.append(target)
    return seen


def load_titles():
    path = BASE / 'lc_titles.json'
    if not path.is_file():
        return {}
    with open(path) as f:
        return json.load(f)


def load_csv(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def parse_pct(s):
    return float(s.rstrip('%'))


def build_company(company, id_to_cats, titles):
    company_dir = REPO_ROOT / company
    if not company_dir.is_dir():
        print(f"[skip] {company}: directory not found")
        return None

    timeframes = {
        'all': company_dir / 'all.csv',
        '30d': company_dir / 'thirty-days.csv',
        '3m': company_dir / 'three-months.csv',
        '6m': company_dir / 'six-months.csv',
        '6m_plus': company_dir / 'more-than-six-months.csv',
    }

    problems = {}
    for tf, path in timeframes.items():
        if not path.is_file():
            continue
        for row in load_csv(path):
            pid = int(row['ID'])
            if pid not in problems:
                t = titles.get(str(pid), {})
                slug = t.get('slug') or row['URL'].rstrip('/').split('/')[-1]
                problems[pid] = {
                    'id': pid,
                    'title': row['Title'],
                    'title_zh': t.get('zh') or row['Title'],
                    'slug': slug,
                    'difficulty': row['Difficulty'],
                    'acceptance': parse_pct(row['Acceptance %']),
                    'freq': {},
                    'categories': id_to_cats.get(pid, []),
                }
            problems[pid]['freq'][tf] = parse_pct(row['Frequency %'])

    problem_list = list(problems.values())

    data = {
        'company': company,
        'problems': problem_list,
        'main_categories': get_main_categories(),
        'labels_en': LABELS_EN,
    }

    html = (HTML_TEMPLATE
            .replace('__COMPANY__', company.title())
            .replace('__DATA__', json.dumps(data, ensure_ascii=False, separators=(',', ':'))))

    out_path = BASE / f'{company}.html'
    out_path.write_text(html, encoding='utf-8')
    categorized = sum(1 for p in problem_list if p['categories'])
    print(f"[ok] {company}: {len(problem_list)} problems ({categorized} categorized) -> {out_path.name}")
    return {
        'company': company,
        'total': len(problem_list),
        'categorized': categorized,
    }


def build_index(stats):
    cards = []
    for s in stats:
        if s is None:
            continue
        cards.append(f"""
        <a class="card" href="{s['company']}.html" data-total="{s['total']}" data-categorized="{s['categorized']}">
          <div class="card-title">{s['company'].title()}</div>
          <div class="card-num">{s['total']}</div>
          <div class="card-sub"></div>
        </a>""")
    html = INDEX_TEMPLATE.replace('__CARDS__', '\n'.join(cards))
    (BASE / 'index.html').write_text(html, encoding='utf-8')
    print(f"[ok] index.html")


def main():
    companies = sys.argv[1:] or DEFAULT_COMPANIES
    id_to_cats = build_id_to_categories()
    titles = load_titles()
    print(f"Loaded {len(titles)} problem titles")
    stats = [build_company(c, id_to_cats, titles) for c in companies]
    build_index([s for s in stats if s])


